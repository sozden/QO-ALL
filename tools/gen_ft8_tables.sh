#!/bin/sh
# Generates src/ft8/tables.rs from a WSJT-X checkout (GPL-3.0):
#   git clone --depth 1 --sparse https://git.code.sf.net/p/wsjt/wsjtx wsjtx
#   git -C wsjtx sparse-checkout set lib/ft8
#   tools/gen_ft8_tables.sh wsjtx/lib/ft8 > src/ft8/tables.rs
# The tables were taken from commit b4f9a43 (2025-02-04).
ref="$1"
echo '//! FT8 code tables, from WSJT-X (lib/ft8/ldpc_174_91_c_generator.f90 and'
echo '//! ldpc_174_91_c_parity.f90, commit b4f9a43, GPL-3.0; K1JT, K9AN, G4WJS and others).'
echo '//! Only the tables are taken; generated by a script, not edited by hand.'
echo
echo '/// Generator of the (174,91) LDPC code: row i gives parity bit i as a 91-bit mask'
echo '/// (hex, most significant bit = message bit 1).'
echo 'pub const GENERATOR: [&str; 83] = ['
sed -n 's/^ *"\([0-9a-f]\{23\}\)".*/    "\1",/p' "$ref/ldpc_174_91_c_generator.f90"
echo '];'
echo
echo '/// For each of the 174 code bits, the three parity checks it takes part in (1-based).'
echo 'pub const MN: [[u8; 3]; 174] = ['
sed -n '2,175p' "$ref/ldpc_174_91_c_parity.f90" | sed 's/[&\/]//g' | awk -F',' '{gsub(/ /,""); printf "    [%s, %s, %s],\n", $1, $2, $3}'
echo '];'
